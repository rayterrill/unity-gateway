_AUTH_PLUGIN_V1_TEMPLATE = """// Generated by ucode. Keep Databricks auth fresh for model requests.
import { execFile } from "node:child_process"
import { promisify } from "node:util"

const DATABRICKS_PROVIDERS = new Set([
  "databricks-anthropic",
  "databricks-google",
  "databricks-oss",
])
const AUTH_COMMAND = __AUTH_COMMAND__
const REFRESH_SKEW_MS = 120_000
const run = promisify(execFile)

let accessToken
let expiresAt = 0
let refreshPromise

function cacheToken(value) {
  accessToken = value
  expiresAt = Infinity
  try {
    const claims = JSON.parse(Buffer.from(value.split(".")[1], "base64url").toString())
    if (typeof claims.exp === "number") expiresAt = claims.exp * 1000
  } catch {}
}

async function mintToken() {
  try {
    const { stdout } = await run(AUTH_COMMAND[0], AUTH_COMMAND.slice(1), { encoding: "utf8" })
    const token = stdout.trim()
    if (!token) throw new Error("returned an empty token")
    cacheToken(token)
  } catch (error) {
    const detail = String(error.stderr || error.message || "").trim()
    throw new Error("ug auth-token failed" + (detail ? ": " + detail : ""))
  }
}

function refreshToken() {
  if (!refreshPromise) refreshPromise = mintToken().finally(() => { refreshPromise = undefined })
  return refreshPromise
}

function requestWithToken(input, init, token) {
  const headers = new Headers(input instanceof Request ? input.headers : undefined)
  new Headers(init?.headers).forEach((value, key) => headers.set(key, value))
  headers.set("Authorization", "Bearer " + token)
  return { ...init, headers }
}

async function databricksFetch(input, init) {
  if (!accessToken || expiresAt <= Date.now() + REFRESH_SKEW_MS) await refreshToken()
  const attemptedToken = accessToken
  const response = await fetch(input, requestWithToken(input, init, attemptedToken))
  if (response.status !== 401) return response

  // Another concurrent request may already have refreshed this token.
  if (accessToken === attemptedToken) await refreshToken()
  return fetch(input, requestWithToken(input, init, accessToken))
}

export const UcodeDatabricksAuth = async () => ({
  config: async (config) => {
    for (const providerID of DATABRICKS_PROVIDERS) {
      const options = config.provider?.[providerID]?.options
      if (!options) continue
      if (!accessToken && typeof options.apiKey === "string") cacheToken(options.apiKey)
      options.fetch = databricksFetch
    }
  },
})
"""

_AUTH_PLUGIN_V2_TEMPLATE = """// Generated by ucode. Keep Databricks OAuth fresh for OpenCode V2 requests.
import { execFile } from "node:child_process"
import { promisify } from "node:util"

const DATABRICKS_PROVIDERS = new Set([
  "databricks-anthropic",
  "databricks-google",
  "databricks-oss",
])
const AUTH_COMMAND = __AUTH_COMMAND__
const REFRESH_SKEW_MS = 120_000
const run = promisify(execFile)

let accessToken
let expiresAt = 0
let refreshPromise

function cacheToken(value) {
  accessToken = value
  // The CLI currently returns JWTs. Give an opaque token a bounded cache life too.
  expiresAt = Date.now() + 55 * 60_000
  try {
    const claims = JSON.parse(Buffer.from(value.split(".")[1], "base64url").toString())
    if (typeof claims.exp === "number") expiresAt = claims.exp * 1000
  } catch {}
}

async function mintToken() {
  try {
    const { stdout } = await run(AUTH_COMMAND[0], AUTH_COMMAND.slice(1), { encoding: "utf8" })
    const value = stdout.trim()
    if (!value) throw new Error("returned an empty token")
    cacheToken(value)
  } catch (error) {
    const detail = String(error.stderr || error.message || "").trim()
    throw new Error("ug auth-token failed" + (detail ? ": " + detail : ""))
  }
}

function refreshToken() {
  if (!refreshPromise) {
    refreshPromise = mintToken().finally(() => { refreshPromise = undefined })
  }
  return refreshPromise
}

async function token() {
  if (!accessToken || expiresAt <= Date.now() + REFRESH_SKEW_MS) await refreshToken()
  return accessToken
}

// OpenCode V2 accepts a default definition with id and setup. No npm plugin
// dependency is needed for this local file; Plugin.define is an identity helper.
export default {
  id: "ucode.databricks-auth",
  async setup(ctx) {
    await ctx.session.hook("http.request", async (event) => {
      if (!DATABRICKS_PROVIDERS.has(event.model?.providerID)) return
      event.request.headers.set("authorization", "Bearer " + await token())
    })
  },
}
"""


def _parse_version(value: str) -> tuple[int, int, int] | None:
    match = re.search(r"(\d+)\.(\d+)\.(\d+)", value)
    if match is None:
        return None
    major, minor, patch = match.groups()
    return int(major), int(minor), int(patch)


def installed_major_version() -> int:
    """Select the config and plugin contract of the installed OpenCode binary."""
    version = agent_version(SPEC["binary"])
    parsed = _parse_version(version)
    if parsed is None:
        raise RuntimeError(f"Cannot determine OpenCode version from {version!r}.")
    return parsed[0]


def _minimum_version_message() -> str | None:
    installed = agent_version(SPEC["binary"])
    parsed = _parse_version(installed)
    if parsed is None or parsed >= MINIMUM_OPENCODE_VERSION:
        return None
    return (
        f"OpenCode {installed} is too old. ucode requires OpenCode "
        f"{MINIMUM_OPENCODE_VERSION_TEXT} or newer for renewable Databricks authentication."
    )


def minimum_version_error() -> str | None:
    message = _minimum_version_message()
    if message is None:
        return None
    return f"{message} Update it with `npm install -g {SPEC['package']}`."


def render_auth_plugin(state: dict, *, major_version: int = 1) -> str:
    """Render the local OpenCode plugin that refreshes Databricks auth on demand."""
    argv = build_auth_token_argv(
        state["workspace"],
        state.get("profile"),
        use_pat=bool(state.get("use_pat")),
    )
    # A 401 must not return the same still-unexpired cached credential.
    argv.append("--force-refresh")
    template = _AUTH_PLUGIN_V2_TEMPLATE if major_version >= 2 else _AUTH_PLUGIN_V1_TEMPLATE
    return template.replace("__AUTH_COMMAND__", json.dumps(argv))


def write_auth_plugin(state: dict, *, major_version: int = 1) -> None:
    """Install the auto-discovered hook in OpenCode's shared config."""
    # Derive the path so tests that redirect OPENCODE_CONFIG_PATH stay isolated.
    path = OPENCODE_CONFIG_PATH.parent / "plugin" / OPENCODE_AUTH_PLUGIN_PATH.name
    from ucode.desktop_config import backup_shared_path

    backup_shared_path(path, OPENCODE_BACKUP_PATH.with_name("opencode-desktop-plugin.backup.js"))
    write_text_file(path, render_auth_plugin(state, major_version=major_version))


def _resolve_model_selector(model: str, opencode_models: dict[str, list[str]]) -> str:
    """Return an OpenCode model selector in provider/model form when possible."""
    if model.startswith(("databricks-anthropic/", "databricks-google/", "databricks-oss/")):
        return model

    anthropic_models = opencode_models.get("anthropic") or []
    if model in anthropic_models:
        return f"databricks-anthropic/{model}"

    gemini_models = opencode_models.get("gemini") or []
    if model in gemini_models:
        return f"databricks-google/{model}"

    oss_models = opencode_models.get("oss") or []
    if model in oss_models:
        return f"databricks-oss/{model}"

    return model


def resolve_explicit_model(model: str, state: dict) -> str:
    """Resolve and validate a model explicitly selected for an OpenCode launch.

    Databricks model ids are exposed in family buckets in ucode state, while
    OpenCode addresses those models through managed provider ids. Other
    provider/model selectors belong to OpenCode and are passed through.
    """
    selector = model.strip()
    if not selector:
        raise RuntimeError("OpenCode model must not be empty.")

    opencode_models = state.get("opencode_models") or {}
    resolved = _resolve_model_selector(selector, opencode_models)
    if "/" not in selector:
        if resolved != selector:
            return resolved
        raise RuntimeError(
            f"OpenCode model '{selector}' is not configured. "
            "Choose a discovered model id or pass a provider/model selector."
        )

    provider, _, model_id = selector.partition("/")
    if not provider or not model_id:
        raise RuntimeError("OpenCode model selector must use provider/model form.")
    managed_providers = {path[-1] for path in PROVIDER_KEYS}
    if provider not in managed_providers:
        return selector

    if _resolve_model_selector(model_id, opencode_models) == selector:
        return selector
    raise RuntimeError(
        f"OpenCode model '{selector}' is not configured for managed provider '{provider}'."
    )


def _oss_model_overlay(model: str, ua_header: dict[str, str]) -> dict:
    """Per-model overlay for an OSS model entry.

    All OSS models carry the User-Agent header; models with known token limits
    also pin `limit` (context + output) so OpenCode clamps `max_tokens` to a
    value the gateway accepts. OpenCode's schema requires both fields together,
    so the limits table always supplies both."""
    overlay: dict = {"headers": ua_header}
    limits = model_token_limits(model)
    if limits is not None:
        overlay["limit"] = limits
    return overlay


def _model_headers() -> dict[str, str]:
    headers = {"User-Agent": f"ucode/{ug_version()} opencode/{agent_version('opencode')}"}
    request_tags = request_tags_header_value()
    if request_tags:
        headers[AI_GATEWAY_REQUEST_TAGS_HEADER] = request_tags
    return headers


def render_overlay(
    model: str,
    token: str,
    opencode_base_urls: dict[str, str],
    opencode_models: dict[str, list[str]],
    *,
    major_version: int = 1,
) -> tuple[dict, list[list[str]]]:
    """Return (overlay, managed_key_paths) for opencode.json."""
    if major_version >= 2:
        return _render_overlay_v2(model, opencode_base_urls, opencode_models)

    auth_headers = {"Authorization": f"Bearer {token}"}
    # OpenCode hardcodes `User-Agent: opencode/<ver>` in session/llm.ts for
    # every provider, after the AI SDK's combineHeaders. The provider-level
    # `headers` are clobbered by that injection, but per-model `headers` are
    # merged AFTER and win — so the UA must live on each model entry.
    # Per-model headers. Like the UA, request tags must ride here (not on the
    # provider `options`), since OpenCode's per-model `headers` win over the
    # provider-level ones after its own UA injection.
    ua_header = _model_headers()

    anthropic_models = opencode_models.get("anthropic") or []
    gemini_models = opencode_models.get("gemini") or []
    oss_models = opencode_models.get("oss") or []

    providers: dict = {}
    keys: list[list[str]] = [["model"]]
    if anthropic_models:
        # @ai-sdk/anthropic injects `eager_input_streaming: true` on tool defs;
        # the Databricks gateway's strict validator rejects it. opencode's
        # auto-disable in transform.ts skips models whose id contains "claude",
        # so we opt out per-model. The setting lives in per-call providerOptions,
        # which opencode reads from `models.<m>.options`, not provider `options`.
        anthropic_model_overlay = {
            "headers": ua_header,
            "options": {"toolStreaming": False},
        }
        providers["databricks-anthropic"] = {
            "npm": "@ai-sdk/anthropic",
            "options": {
                "baseURL": opencode_base_urls["anthropic"],
                "apiKey": token,
                "headers": auth_headers,
            },
            "models": dict.fromkeys(anthropic_models, anthropic_model_overlay),
        }
        keys.append(["provider", "databricks-anthropic"])
    if gemini_models:
        providers["databricks-google"] = {
            "npm": "@ai-sdk/google",
            "options": {
                "baseURL": opencode_base_urls["gemini"],
                "apiKey": token,
                "headers": auth_headers,
            },
            "models": {m: {"headers": ua_header} for m in gemini_models},
        }
        keys.append(["provider", "databricks-google"])
    if oss_models:
        providers["databricks-oss"] = {
            "npm": "@ai-sdk/openai",
            "options": {
                "baseURL": opencode_base_urls["oss"],
                "apiKey": token,
                "headers": auth_headers,
            },
            "models": {m: _oss_model_overlay(m, ua_header) for m in oss_models},
        }
        keys.append(["provider", "databricks-oss"])

    overlay: dict = {"model": _resolve_model_selector(model, opencode_models)}
    if providers:
        overlay["provider"] = providers
    return overlay, keys


def _render_overlay_v2(
    model: str,
    base_urls: dict[str, str],
    models: dict[str, list[str]],
) -> tuple[dict, list[list[str]]]:
    """V2 provider settings contain no bearer token; the request hook supplies it."""
    ua_header = _model_headers()
    providers: dict = {}
    keys: list[list[str]] = [["model"]]
    for family, provider_id, package, url_key in (
        ("anthropic", "databricks-anthropic", "@opencode/ai/providers/anthropic", "anthropic"),
        ("gemini", "databricks-google", "@opencode/ai/providers/google", "gemini"),
        ("oss", "databricks-oss", "@opencode/ai/providers/openai-compatible", "oss"),
    ):
        family_models = models.get(family) or []
        if not family_models:
            continue
        entries = {
            name: _oss_model_overlay(name, ua_header) if family == "oss" else {"headers": ua_header}
            for name in family_models
        }
        if family == "anthropic":
            for entry in entries.values():
                entry["settings"] = {"toolStreaming": False}
        providers[provider_id] = {
            "name": f"Databricks {family} (uCode)",
            "env": ["DATABRICKS_TOKEN"],
            "package": package,
            "settings": {"baseURL": base_urls[url_key]},
            "models": entries,
        }
        keys.append(["providers", provider_id])
    overlay: dict = {"model": _resolve_model_selector(model, models)}
    if providers:
        overlay["providers"] = providers
    return overlay, keys


def remove_managed_providers(config: dict) -> None:
    """Remove only ucode's entries across V1 and V2 before replacing them."""
    for field in ("provider", "providers"):
        providers = config.get(field)
        if not isinstance(providers, dict):
            continue
        for provider_id in (
            "databricks-anthropic",
            "databricks-google",
            "databricks-openai",
            "databricks-oss",
        ):
            providers.pop(provider_id, None)
        if not providers:
            config.pop(field)


def _read_shared_config() -> dict:
    """Never overwrite an existing user config that cannot be parsed."""
    if not OPENCODE_CONFIG_PATH.exists():
        return {}
    try:
        value = json.loads(OPENCODE_CONFIG_PATH.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise RuntimeError(
            f"Cannot update OpenCode settings at {OPENCODE_CONFIG_PATH}: {exc}"
        ) from exc
    if not isinstance(value, dict):
        raise RuntimeError(f"OpenCode settings at {OPENCODE_CONFIG_PATH} must be a JSON object.")
    return value


def _migrate_user_mcp_entries(existing: dict, state: dict) -> None:
    """Carry developer registrations from the old isolated file on first shared write."""
    names = {
        server.get("name")
        for server in state.get("mcp_servers") or []
        if isinstance(server, dict) and "opencode" in (server.get("clients") or [])
    }
    if not names or not LEGACY_OPENCODE_CONFIG_PATH.exists():
        return
    try:
        legacy = json.loads(LEGACY_OPENCODE_CONFIG_PATH.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError):
        return
    old_servers = legacy.get("mcp") if isinstance(legacy, dict) else None
    if not isinstance(old_servers, dict):
        return
    shared_servers = existing.get("mcp")
    if not isinstance(shared_servers, dict):
        shared_servers = {}
    for name in names:
        if isinstance(name, str) and name in old_servers:
            shared_servers.setdefault(name, old_servers[name])
    if shared_servers:
        existing["mcp"] = shared_servers


def write_tool_config(
    state: dict,
    model: str,
    token: str | None = None,
) -> tuple[dict, str]:
    from ucode.desktop_config import backup_shared_path

    backup_shared_path(OPENCODE_CONFIG_PATH, OPENCODE_BACKUP_PATH)
    major_version = installed_major_version()
    if token is None:
        token = get_databricks_token(state["workspace"], state.get("profile"))
    opencode_base_urls = state.get("base_urls", {}).get("opencode") or build_opencode_base_urls(
        state["workspace"]
    )
    overlay, managed_keys = render_overlay(
        model,
        token,
        opencode_base_urls,
        state.get("opencode_models") or {},
        major_version=major_version,
    )
    existing = _read_shared_config()
    _migrate_user_mcp_entries(existing, state)
    write_auth_plugin(state, major_version=major_version)
    remove_managed_providers(existing)
    merged = deep_merge_dict(existing, overlay)
    write_json_file(OPENCODE_CONFIG_PATH, merged)
    state = mark_tool_managed(state, "opencode", managed_keys)
    save_state(state)
    return state, token


def build_mcp_server_entry(argv: list[str]) -> dict:
    # A `local` MCP server runs a command over stdio; `command` is the full
    # argv. ug registers the `ug mcp-proxy ...` bridge here so OpenCode
    # never speaks HTTP+bearer directly — the proxy mints fresh tokens itself.
    return {
        "type": "local",
        "command": list(argv),
        "enabled": True,
    }


def write_mcp_server_config(name: str, argv: list[str]) -> bool:
    from ucode.desktop_config import backup_shared_path

    backup_shared_path(OPENCODE_CONFIG_PATH, OPENCODE_BACKUP_PATH)
    existing = _read_shared_config()
    mcp_servers = existing.get("mcp")
    if not isinstance(mcp_servers, dict):
        mcp_servers = {}
    removed = name in mcp_servers
    mcp_servers[name] = build_mcp_server_entry(argv)
    existing["mcp"] = mcp_servers
    write_json_file(OPENCODE_CONFIG_PATH, existing)
    return removed


def remove_mcp_server_config(name: str) -> bool:
    existing = _read_shared_config()
    mcp_servers = existing.get("mcp")
    if not isinstance(mcp_servers, dict) or name not in mcp_servers:
        return False
    mcp_servers.pop(name)
    existing["mcp"] = mcp_servers
    write_json_file(OPENCODE_CONFIG_PATH, existing)
    return True


def write_user_mcp_servers(add: dict[str, dict], remove: set[str]) -> set[str]:
    """Apply ``add``/``remove`` to OpenCode's `mcp` table in a single read-modify-write. Returns the names actually removed."""
    from ucode.desktop_config import backup_shared_path

    backup_shared_path(OPENCODE_CONFIG_PATH, OPENCODE_BACKUP_PATH)
    _read_shared_config()  # Reject malformed user settings before the diff writer reads them.
    return apply_json_mcp_diff(OPENCODE_CONFIG_PATH, "mcp", add, remove)


def default_model(state: dict) -> str | None:
    if isinstance(state.get("opencode_default_model"), str):
        return state.get("opencode_default_model")
    opencode_models = state.get("opencode_models") or {}
    anthropic = opencode_models.get("anthropic") or []
    if anthropic:
        return anthropic[0]
    gemini = opencode_models.get("gemini") or []
    if gemini:
        return gemini[0]
    oss = opencode_models.get("oss") or []
    return oss[0] if oss else None


def _configure_launch(state: dict, model: str | None = None) -> str:
    model = model or default_model(state)
    if not model:
        raise RuntimeError("No OpenCode model is configured.")
    _, token = write_tool_config(state, model)
    return token


def build_runtime_env(token: str, state: dict | None = None) -> dict[str, str]:
    env = os.environ.copy()
    env["OAUTH_TOKEN"] = token
    return env


def launch(state: dict, tool_args: list[str], *, options: LaunchOptions) -> None:
    """Launch OpenCode with the selected model and on-demand token refresh."""
    model = explicit_model_arg_value(tool_args) or options.user_pinned_model
    if model is not None:
        model = resolve_explicit_model(model, state)
    token = _configure_launch(state)
    env = build_runtime_env(token, state)

    if model is not None and not has_explicit_model_arg(tool_args):
        try:
            separator = tool_args.index("--")
        except ValueError:
            separator = len(tool_args)
        tool_args = [
            *tool_args[:separator],
            "--model",
            model,
            *tool_args[separator:],
        ]

    proc = subprocess_cross_os.popen([SPEC["binary"], *tool_args], env=env)
    try:
        returncode = proc.wait()
    except KeyboardInterrupt:
        proc.send_signal(signal.SIGINT)
        returncode = proc.wait()

    raise SystemExit(returncode)


def validate_cmd(binary: str) -> list[str]:
    return [binary, "run", "say hi in 5 words or less"]
